export function getAllTools(): ToolDefinition[] {
  return TOOLS;
}

export function getToolBySlug(slug: string): ToolDefinition | undefined {
  if (slug === "passport-photo") {
    return TOOLS.find((tool) => tool.slug === "photo-tool" || tool.id === "photo-tool");
  }
  return TOOLS.find((tool) => tool.slug === slug || tool.id === slug);
}

export function getCategories(): CategoryDefinition[] {
  return CATEGORIES;
}

export function getToolsByCategory(category: ToolCategory): ToolDefinition[] {
  return TOOLS.filter((tool) => tool.category === category);
}

export function searchTools(query: string): ToolDefinition[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return TOOLS;

  return TOOLS.filter((tool) => {
    const matchName = tool.name.toLowerCase().includes(clean);
    const matchDesc = tool.description.toLowerCase().includes(clean);
    const matchCat = tool.category.toLowerCase().includes(clean);
    return matchName || matchDesc || matchCat;
  });
}
